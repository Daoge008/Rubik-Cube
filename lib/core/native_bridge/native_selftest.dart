/// One scrambled state plus the solver results measured on the host (x86_64).
///
/// The facelet string is the input; the three numbers are the reference the
/// phone has to reproduce. They are compared by *length* rather than by exact
/// move string, because both solvers are allowed to return any shortest answer
/// - what must not change across architectures is how long the answer is.
class DeviceVector {
  const DeviceVector(
    this.facelets,
    this.hostKociembaLen,
    this.hostCfopStages,
    this.hostCfopMoves,
  );

  final String facelets;
  final int hostKociembaLen;
  final int hostCfopStages;
  final int hostCfopMoves;
}

