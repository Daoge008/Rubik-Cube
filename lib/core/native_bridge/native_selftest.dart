/// `U R F D L B` order, the same layout the native core uses.
const String kSolvedFacelets =
    'UUUUUUUUURRRRRRRRRFFFFFFFFFDDDDDDDDDLLLLLLLLLBBBBBBBBB';

/// The solved state with one sticker repainted, so the colour census no longer
/// balances. A validator that accepts this is not validating anything.
const String kIllegalFacelets =
    'UUUUUUUUURRRRRRRRRFFFFFFFFFDDDDDDDDDLLLLLLLLLBBBBBBBBU';

class SelfTestCheck {
  const SelfTestCheck(this.label, this.passed, this.detail);

  final String label;
  final bool passed;
  final String detail;
}

class NativeSelfTestResult {
  const NativeSelfTestResult({
    required this.checks,
    required this.log,
    required this.kociembaMicros,
    required this.cfopMicros,
    required this.coldStartMicros,
  });

  final List<SelfTestCheck> checks;

  /// One `PASS|FAIL | label | detail` line per check, mirrored to logcat so a
  /// device run can be inspected over adb without looking at the screen.
  final String log;

  final int kociembaMicros;
  final int cfopMicros;

  /// First solver call on a fresh process, which also builds the pruning
  /// tables. Orders of magnitude slower than the rest; the gap is what the
  /// app has to hide behind a warm-up.
  final int coldStartMicros;

  bool get allPassed => checks.every((c) => c.passed);

  int get failureCount => checks.where((c) => !c.passed).length;
}

/// Runs the on-device acceptance test for `librubik_core.so`.
///
/// Deliberately exercises *scrambled* states: the solved state takes a trivial
/// branch in both solvers and would pass even if the pruning tables were
/// completely wrong. Yields to the event loop between vectors so a slow device
/// can still paint progress instead of tripping the watchdog.
Future<NativeSelfTestResult> runNativeSelfTest({
  void Function(int done, int total)? onProgress,
}) async {
  final engine = RubikFfiBridge.instance;
  final checks = <SelfTestCheck>[];
  final log = StringBuffer();

  void record(String label, bool passed, String detail) {
    checks.add(SelfTestCheck(label, passed, detail));
    log.writeln('${passed ? 'PASS' : 'FAIL'} | $label | $detail');
  }

  record(
    '原生库 librubik_core.so',
    engine.isLoaded,
    engine.isLoaded ? '已加载，12 个 FFI 符号解析成功' : (engine.loadError ?? '加载失败'),
  );
  record(
    '管线句柄 init_cube_pipeline',
    engine.isPipelineInitialized,
    engine.isPipelineInitialized ? '上下文已创建' : (engine.pipelineError ?? '未初始化'),
  );

  final solvedError = engine.validate(kSolvedFacelets);
  record('validate(已还原)', solvedError == null,
      solvedError ?? '通过颜色计数与守恒校验');

  final illegalError = engine.validate(kIllegalFacelets);
  record(
    'validate(非法态必须拒绝)',
    illegalError != null,
    illegalError ?? '**接受了非法状态，校验器形同虚设**',
  );

  final solvedSolution = engine.solveKociemba(kSolvedFacelets);
  record('solve(已还原)', solvedSolution == 'SOLVED',
      solvedSolution == 'SOLVED' ? '正确识别' : solvedSolution);

  if (kDeviceVectors.isEmpty) {
    return NativeSelfTestResult(
      checks: checks,
      log: log.toString(),
      kociembaMicros: 0,
      cfopMicros: 0,
      coldStartMicros: 0,
    );
  }

  // Cold start: the first real solve also builds both pruning tables, so it is
  // timed on its own instead of polluting the per-vector average. Yield first
  // so whoever is showing progress gets to paint before the thread blocks.
  await Future<void>.delayed(const Duration(milliseconds: 64));
  final coldWatch = Stopwatch()..start();
  final firstKociemba = engine.solveKociemba(kDeviceVectors.first.facelets);
  coldWatch.stop();
  final coldStartMicros = coldWatch.elapsedMicroseconds;
  record('冷启动首次求解（含建表）', firstKociemba.isNotEmpty,
      '${(coldStartMicros / 1000).toStringAsFixed(0)} ms');

  var kociembaMicros = 0;
  var cfopMicros = 0;
  var matches = 0;
  var lengthMismatches = <String>[];
  var cfopProblems = <String>[];
  var structureProblems = <String>[];
  final layouts = <String>[];

  for (var i = 0; i < kDeviceVectors.length; i++) {
    final v = kDeviceVectors[i];

    final kocWatch = Stopwatch()..start();
    final solution = engine.solveKociemba(v.facelets);
    kociembaMicros += kocWatch.elapsedMicroseconds;

    final cfopWatch = Stopwatch()..start();
    final cfopJson = engine.generateCfopJson(v.facelets);
    cfopMicros += cfopWatch.elapsedMicroseconds;

    final moves = _moveCount(solution);
    if (moves == v.hostKociembaLen) {
      matches++;
    } else {
      lengthMismatches.add('#$i 设备 $moves vs 主机 ${v.hostKociembaLen}'
          '${moves == null ? '（无法解析："$solution"）' : ''}');
    }

    final parsed = _inspectCfop(cfopJson);
    layouts.add('#$i stages=${parsed.stages} [${parsed.layout.join(', ')}]');
    if (parsed.stages != v.hostCfopStages) {
      cfopProblems.add('#$i 阶段数 设备 ${parsed.stages} vs 主机 ${v.hostCfopStages}');
    }
    if (parsed.missingFormula > 0) {
      cfopProblems.add('#$i 有 ${parsed.missingFormula} 个阶段 formula 为空');
    }
    if (parsed.missingAlgorithms > 0) {
      structureProblems.add('#$i 有 ${parsed.missingAlgorithms} 个阶段未给出算法名');
    }
    if (parsed.missingText > 0) {
      structureProblems.add('#$i 有 ${parsed.missingText} 个阶段的讲解文本为空');
    }

    onProgress?.call(i + 1, kDeviceVectors.length);
    await Future<void>.delayed(Duration.zero);
  }

  final n = kDeviceVectors.length;
  log.writeln('--- CFOP 阶段分解（逐行对比 tools/native_tests 的 gen_vectors 输出）---');
  for (final line in layouts) {
    log.writeln(line);
  }
  record(
    'Kociemba 解长度与主机一致',
    lengthMismatches.isEmpty,
    lengthMismatches.isEmpty
        ? '$matches/$n 一致，平均 ${(kociembaMicros / 1000 / n).toStringAsFixed(0)} ms'
        : lengthMismatches.join('；'),
  );
  record(
    'CFOP 阶段划分与主机一致',
    cfopProblems.isEmpty,
    cfopProblems.isEmpty
        ? '$n/$n 一致，平均 ${(cfopMicros / 1000 / n).toStringAsFixed(0)} ms'
        : cfopProblems.join('；'),
  );
  record(
    'CFOP 教学字段完整（算法名 / 讲解）',
    structureProblems.isEmpty,
    structureProblems.isEmpty ? '每阶段均带公式名与讲解' : structureProblems.join('；'),
  );

  await _runVisionSelfTest(engine, record, log);

  return NativeSelfTestResult(
    checks: checks,
    log: log.toString(),
    kociembaMicros: kociembaMicros,
    cfopMicros: cfopMicros,
    coldStartMicros: coldStartMicros,
  );
}

