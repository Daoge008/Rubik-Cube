/// A synthetic I420 frame: a 3x3 grid of solid stickers inside the guide box
/// and black outside it, which is what the camera sees when a cube is held over
/// a dark table.
///
/// This is the only way to exercise the camera path without a camera. It checks
/// the YUV unpacking, the sampling geometry, the colour classification, the
/// white balance bootstrap and the six-face stitch, all on the device's own
/// ARM build - the half of the engine that a host test can only approximate.
class _SyntheticFrame {
  _SyntheticFrame(this.width, this.height)
      : y = Uint8List(width * height),
        u = Uint8List((width ~/ 2) * (height ~/ 2)),
        v = Uint8List((width ~/ 2) * (height ~/ 2));

  final int width;
  final int height;
  final Uint8List y;
  final Uint8List u;
  final Uint8List v;

  int get yStride => width;
  int get uvStride => width ~/ 2;

  /// Sticker colours, close to but not equal to the native anchors so the test
  /// measures classification rather than a lookup.
  static const List<List<int>> _stickerRgb = <List<int>>[
    <int>[250, 250, 250], // white
    <int>[210, 40, 50], // red
    <int>[40, 175, 80], // green
    <int>[250, 220, 60], // yellow
    <int>[235, 150, 40], // orange
    <int>[35, 95, 195], // blue
  ];

  /// Paints nine sticker colours into a centred 3x3 grid.
  ///
  /// The geometry mirrors `kGuideSideFraction` on the Dart side and
  /// `sampleFaceGrid`'s default on the native side; if those ever drift apart
  /// this test starts reading the black background and fails loudly.
  void fill(List<int> cells) {
    final side = math.min(width, height) * 0.72;
    final left = (width - side) / 2;
    final top = (height - side) / 2;
    final cell = side / 3;

    for (var py = 0; py < height; py++) {
      for (var px = 0; px < width; px++) {
        var yy = 16, uu = 128, vv = 128; // black

        final fx = px - left;
        final fy = py - top;
        if (fx >= 0 && fy >= 0 && fx < side && fy < side) {
          final gx = math.min(2, (fx / cell).floor());
          final gy = math.min(2, (fy / cell).floor());
          final rgb = _stickerRgb[cells[gy * 3 + gx]];
          yy = (0.257 * rgb[0] + 0.504 * rgb[1] + 0.098 * rgb[2] + 16)
              .round()
              .clamp(0, 255);
          uu = (-0.148 * rgb[0] - 0.291 * rgb[1] + 0.439 * rgb[2] + 128)
              .round()
              .clamp(0, 255);
          vv = (0.439 * rgb[0] - 0.368 * rgb[1] - 0.071 * rgb[2] + 128)
              .round()
              .clamp(0, 255);
        }

        y[py * width + px] = yy;
        if (py.isEven && px.isEven) {
          final idx = (py ~/ 2) * uvStride + px ~/ 2;
          u[idx] = uu;
          v[idx] = vv;
        }
      }
    }
  }
}

const Map<String, int> _kColorIndexByFacelet = <String, int>{
  'U': 0,
  'R': 1,
  'F': 2,
  'D': 3,
  'L': 4,
  'B': 5,
};

/// Drives the whole camera path with synthetic frames and checks that six
/// scanned faces come back out as a solvable cube.
Future<void> _runVisionSelfTest(
  RubikFfiBridge engine,
  void Function(String label, bool passed, String detail) record,
  StringBuffer log,
) async {
  final facelets = kDeviceVectors.first.facelets;
  final frame = _SyntheticFrame(240, 240);
  const framesPerFace = 9; // one more than the vote window

  engine.resetScanner();

  for (var face = 0; face < 6; face++) {
    final cells = <int>[];
    for (var k = 0; k < 9; k++) {
      cells.add(_kColorIndexByFacelet[facelets[face * 9 + k]]!);
    }
    frame.fill(cells);

    for (var f = 0; f < framesPerFace; f++) {
      engine.processFrameYuv(
        yPlane: frame.y,
        yStride: frame.yStride,
        yPixelStride: 1,
        uPlane: frame.u,
        uStride: frame.uvStride,
        uPixelStride: 1,
        vPlane: frame.v,
        vStride: frame.uvStride,
        vPixelStride: 1,
        width: frame.width,
        height: frame.height,
        rotationDegrees: 0,
      );
    }

    await Future<void>.delayed(Duration.zero);
  }

  final lockedFaces = engine.getScannedFacesCount();
  record(
    '视觉扫描：六面识别',
    lockedFaces == 6,
    '$lockedFaces/6 面通过多帧表决',
  );

  final assembled = engine.getScannedCubeString();
  if (assembled == null) {
    record(
      '视觉扫描：六面拼合',
      false,
      '六面已识别但无法拼成合法状态（朝向对齐失败）',
    );
    return;
  }

  log.writeln('识别拼合结果: $assembled');
  log.writeln('原始打乱状态: $facelets');

  final validationError = engine.validate(assembled);
  record(
    '视觉扫描：拼合结果可解',
    validationError == null,
    validationError ?? '通过校验，可交给求解器',
  );
}


/// Number of moves in a native solution string, or `null` when it cannot be
/// parsed. `SOLVED` and `ERROR:` replies are not move lists.
int? _moveCount(String solution) {
  final trimmed = solution.trim();
  if (trimmed.isEmpty || trimmed == 'SOLVED' || trimmed.startsWith('ERROR')) {
    return null;
  }
  return trimmed.split(RegExp(r'\s+')).length;
}

class _CfopInspection {
  int stages = 0;
  int missingFormula = 0;
  int missingAlgorithms = 0;
  int missingText = 0;

  /// `name:moveCount` per stage, in order, for diffing against the host.
  final List<String> layout = <String>[];
}

/// First stage id that is part of the last layer. Cross and the four F2L slots
/// are raw searches with no formula to name; only the last layer stages are
/// supposed to carry named algorithms.
const int _kFirstLastLayerStageId = 5;

_CfopInspection _inspectCfop(String json) {
  final result = _CfopInspection();
  dynamic decoded;
  try {
    decoded = jsonDecode(json);
  } catch (_) {
    return result;
  }
  if (decoded is! List) return result;

  result.stages = decoded.length;
  for (final dynamic entry in decoded) {
    if (entry is! Map) {
      result.missingFormula++;
      continue;
    }
    final formula = entry['formula'];
    final formulaOk = formula is String && formula.trim().isNotEmpty;
    if (!formulaOk) result.missingFormula++;

    final stageId = entry['stageId'];
    final isLastLayer = stageId is int && stageId >= _kFirstLastLayerStageId;

    final algorithms = entry['algorithms'];
    if (isLastLayer && (algorithms is! List || algorithms.isEmpty)) {
      result.missingAlgorithms++;
    }

    final hint = entry['visualHint'];
    final explanation = entry['explanation'];
    final hasHint = hint is String && hint.trim().isNotEmpty;
    final hasExplanation = explanation is String && explanation.trim().isNotEmpty;
    if (!hasHint || !hasExplanation) result.missingText++;

    final name = entry['stageName'];
    final label = name is String ? name : '?';
    final stageTier = entry['stageTier'];
    final tierSuffix = stageTier is int ? '/t$stageTier' : '';
    result.layout.add(
        '$label:${_moveCount(formulaOk ? formula : '') ?? 0}$tierSuffix');
  }
  return result;
}
