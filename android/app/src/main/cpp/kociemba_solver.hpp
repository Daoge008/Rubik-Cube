// ---------------------------------------------------------------------------
// Coordinates
// ---------------------------------------------------------------------------

/// 3^7 = 2187 twists of the first seven corners; the eighth is implied by the
/// twist parity invariant.
inline int twistCoord(const CubieState& s) {
    int t = 0;
    for (int i = 0; i < 7; ++i) t = 3 * t + s.co[i];
    return t;
}

/// 2^11 = 2048 flips of the first eleven edges.
inline int flipCoord(const CubieState& s) {
    int f = 0;
    for (int i = 0; i < 11; ++i) f = 2 * f + s.eo[i];
    return f;
}

/// Which of the four UD-slice edges (FR, FL, BL, BR) occupy which positions,
/// as an index in 0..494. Instead of a hand derived combinatorial formula the
/// 495 subsets of a 12 bit mask are enumerated once, which keeps the encoding
/// trivially auditable.
///
/// Masks are enumerated in *descending* order so that index 0 is the solved
/// configuration (slice edges on positions 8..11). Every coordinate in this
/// file therefore has its goal at value 0, which is what the BFS and the IDA*
/// goal tests rely on.
inline const std::array<uint16_t, 4096>& sliceMaskToIndex() {
    static const std::array<uint16_t, 4096> table = [] {
        std::array<uint16_t, 4096> t{};
        for (auto& v : t) v = 0xFFFF;
        int index = 0;
        for (int mask = 4095; mask >= 0; --mask) {
            int bits = 0;
            for (int b = 0; b < 12; ++b) bits += (mask >> b) & 1;
            if (bits == 4) t[mask] = (uint16_t)index++;
        }
        return t;
    }();
    return table;
}

inline const std::array<uint16_t, 495>& sliceIndexToMask() {
    static const std::array<uint16_t, 495> table = [] {
        std::array<uint16_t, 495> t{};
        int index = 0;
        for (int mask = 4095; mask >= 0; --mask) {
            int bits = 0;
            for (int b = 0; b < 12; ++b) bits += (mask >> b) & 1;
            if (bits == 4) t[index++] = (uint16_t)mask;
        }
        return t;
    }();
    return table;
}

inline int sliceCoord(const CubieState& s) {
    int mask = 0;
    for (int i = 0; i < 12; ++i) {
        if (s.ep[i] >= FR) mask |= 1 << i;
    }
    return sliceMaskToIndex()[mask];
}

/// Lexicographic rank of a permutation (Lehmer code), 0..n!-1.
inline int permRank(const uint8_t* p, int n) {
    int rank = 0;
    for (int i = 0; i < n; ++i) {
        int smaller = 0;
        for (int j = i + 1; j < n; ++j) {
            if (p[j] < p[i]) smaller++;
        }
        rank = rank * (n - i) + smaller;
    }
    return rank;
}

inline void permUnrank(int rank, uint8_t* p, int n) {
    static const int fact[13] = { 1, 1, 2, 6, 24, 120, 720, 5040, 40320,
                                  362880, 3628800, 39916800, 479001600 };
    uint8_t avail[12];
    for (int i = 0; i < n; ++i) avail[i] = (uint8_t)i;
    for (int i = 0; i < n; ++i) {
        const int f = fact[n - 1 - i];
        const int idx = rank / f;
        rank -= idx * f;
        p[i] = avail[idx];
        for (int j = idx; j < n - 1; ++j) avail[j] = avail[j + 1];
    }
}

/// Permutation of the four slice edges among the four slice positions (0..23).
inline int slicePermCoord(const CubieState& s) {
    uint8_t p[4] = {
        (uint8_t)(s.ep[8] - FR), (uint8_t)(s.ep[9] - FR),
        (uint8_t)(s.ep[10] - FR), (uint8_t)(s.ep[11] - FR)
    };
    return permRank(p, 4);
}

/// Permutation of the eight corners (0..40319).
inline int cornerPermCoord(const CubieState& s) {
    uint8_t p[8];
    for (int i = 0; i < 8; ++i) p[i] = (uint8_t)s.cp[i];
    return permRank(p, 8);
}

/// Permutation of the eight non-slice edges over the first eight positions.
inline int edgePermCoord(const CubieState& s) {
    uint8_t p[8];
    for (int i = 0; i < 8; ++i) p[i] = (uint8_t)s.ep[i];
    return permRank(p, 8);
}

/// True when the state already lies in the phase 2 subgroup, i.e. every U/D
/// sticker faces up or down and the slice edges sit in the slice.
inline bool inPhase2Subgroup(const CubieState& s) {
    return twistCoord(s) == 0 && flipCoord(s) == 0 && sliceCoord(s) == 0;
}

